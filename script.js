// ========== DOM ELEMENTS ==========
const html = document.documentElement;
const themeToggle = document.getElementById("theme-toggle");
const langToggle = document.getElementById("lang-toggle");
const langFlag = document.getElementById("lang-flag");
const mobileMenuBtn = document.getElementById("mobileMenuBtn");
const navLinks = document.getElementById("navLinks");
const navOverlay = document.getElementById("navOverlay");

// ========== THEME MANAGEMENT ==========
function setTheme(theme) {
  html.setAttribute("data-theme", theme);
  localStorage.setItem("theme", theme);
  const icon = theme === "light" ? "sun" : "moon";
  themeToggle.innerHTML = `<i class="fas fa-${icon}"></i>`;
}

// ========== LANGUAGE MANAGEMENT ==========
function applyLanguage(lang) {
  if (!["id", "en"].includes(lang)) return;

  html.setAttribute("lang", lang);
  html.setAttribute("data-lang", lang);
  langFlag.textContent = lang === "id" ? "🇮🇩" : "🇬🇧";
  translatePage(lang);
  localStorage.setItem("lang", lang);
}

function translatePage(lang) {
  const dict = translations[lang] || translations.id;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });
}

// ========== MOBILE MENU ==========
function toggleMobileMenu() {
  const isActive = navLinks.classList.toggle("active");
  navOverlay.classList.toggle("active", isActive);
  const icon = isActive ? "times" : "bars";
  mobileMenuBtn.querySelector("i").className = `fas fa-${icon}`;
  document.body.style.overflow = isActive ? "hidden" : "";
}

// ========== SCROLL ANIMATIONS ==========
function initScrollAnimations() {
  const animateObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");
          animateObserver.unobserve(entry.target);
        }
      });
    },
    {
      threshold: 0.15,
      rootMargin: "0px 0px -50px 0px",
    }
  );

  document
    .querySelectorAll(
      ".project-card, .timeline-item, .about-content, .hero-content"
    )
    .forEach((el) => {
      animateObserver.observe(el);
    });
}

// ========== EVENT LISTENERS ==========
function bindEvents() {
  // Theme toggle
  themeToggle?.addEventListener("click", () => {
    const current = html.getAttribute("data-theme") || "light";
    setTheme(current === "light" ? "dark" : "light");
  });

  // Language toggle
  langToggle?.addEventListener("click", () => {
    const current = html.getAttribute("data-lang") || "id";
    const next = current === "id" ? "en" : "id";
    applyLanguage(next);
  });

  // Mobile menu
  mobileMenuBtn?.addEventListener("click", toggleMobileMenu);
  navOverlay?.addEventListener("click", toggleMobileMenu);

  // Close mobile menu on nav link click
  document.querySelectorAll(".nav-link").forEach((link) => {
    link.addEventListener("click", () => {
      if (navLinks.classList.contains("active")) {
        toggleMobileMenu();
      }
    });
  });
}

// ========== INIT ==========
(function init() {
  // Set theme
  const savedTheme = localStorage.getItem("theme") || "light";
  setTheme(savedTheme);

  // Set language
  const savedLang = localStorage.getItem("lang") || "id";
  applyLanguage(savedLang);

  // Bind events & animations
  bindEvents();
  initScrollAnimations();
})();
